//! IQ3_XXS quantizer, ported from llama.cpp-master `ggml/src/ggml-quants.c`
//! (`quantize_row_iq3_xxs_impl` with `grid_size = 256`).
//!
//! The previous `quantize_iq3xxs` in this crate was not an IQ3_XXS encoder at
//! all: it emitted 96 bytes per 256-weight block where the format has 98, and it
//! packed signs as a flat bit array where the format stores four 7-bit
//! `ksigns_iq2xs` indices. It could not round-trip against this crate's own
//! `dequant_iq3xxs`, which is a faithful port of the reference decoder.
//!
//! Reference layout -- `block_iq3_xxs` is `ggml_half d` + `uint8_t qs[96]`
//! (ggml-common.h:405, `static_assert(sizeof(block_iq3_xxs) == 2 + 3*(QK_K/8))`):
//!
//! ```text
//!   d      f16 global scale                     @0..2
//!   qs     one grid index per 32-weight sub-block, 8 of them
//!                                                     @2..66
//!   qs+64  8 x u32 scales_and_signs:
//!              bits 0..6   block_signs[0]   (7-bit ksigns_iq2xs index)
//!              bits 7..13  block_signs[1]
//!              bits 14..20 block_signs[2]
//!              bits 21..27 block_signs[3]
//!              bits 28..31 4-bit scale
//!                                                     @66..98
//! ```
//!
//! `d = fp16(max_scale/31 * 1.0125)` -- the fudge factor is in the reference.
//!
//! The encoder is a per-32-weight vector quantizer: signs are chosen by
//! magnitude parity, then the scale is optimised over 31 candidates against the
//! 256-point grid, with a nearest-neighbour search for off-grid points.

use crate::{Error, Result, f32_to_f16};

/// Weights per super-block.
const QK3XXS: usize = 256;
/// Bytes per super-block: `d` (2) + `qs` (96).
pub const IQ3XXS_BLOCK_BYTES: usize = 98;
/// Largest code the grid can represent (`kMaxQ` in the reference).
const KMAX_Q: i32 = 8;
/// Sub-blocks per super-block.
const N_SUB: usize = QK3XXS / 32;
/// Below this a sub-block is treated as all-zero (`GROUP_MAX_EPS_IQ3_XXS`).
const GROUP_MAX_EPS: f32 = 1e-8;

/// Pick the grid point minimising weighted squared error among the neighbours.
///
/// `offset` is the neighbour-table offset recovered from [`KMAP_Q3XS`]; `xval`
/// and `waux` are the 4 values for this group; `codes` receives the winning code.
fn iq3_find_best_neighbour(
    offset: usize,
    xval: &[f32],
    waux: &[f32],
    scale: f32,
    codes: &mut [i8],
) -> i32 {
    let neighbours = &KNEIGHBORS_Q3XS[offset..];
    let num = neighbours[0] as usize;
    assert!(num > 0, "neighbour table entry {offset} has no neighbours");
    let mut best_d2 = f32::INFINITY;
    let mut grid_index = -1i32;
    for j in 1..=num {
        let pg = &KGRID_Q3XS[neighbours[j] as usize].to_le_bytes();
        let mut d2 = 0.0f32;
        for i in 0..4 {
            let diff = scale * pg[i] as f32 - xval[i];
            d2 += waux[i] * diff * diff;
        }
        if d2 < best_d2 {
            best_d2 = d2;
            grid_index = neighbours[j] as i32;
        }
    }
    assert!(grid_index >= 0, "neighbour search found no grid point");
    let pg = &KGRID_Q3XS[grid_index as usize].to_le_bytes();
    for i in 0..4 {
        codes[i] = ((pg[i] - 1) / 2) as i8;
    }
    grid_index
}

/// Quantize f32 values to IQ3_XXS bytes.
///
/// `data.len()` must be non-zero. The final partial block is zero-padded to 256,
/// matching every other grim-quant IQ encoder (`quant_iq4xs`, `quant_iq3s`, …).
/// Output is `ceil(data.len()/256) * 98` bytes.
pub fn quantize_iq3xxs(data: &[f32]) -> Result<Vec<u8>> {
    if data.is_empty() {
        return Err(Error::Backend(
            "quantize_iq3xxs: empty input".into(),
        ));
    }
    let nbl = data.len().div_ceil(QK3XXS);
    let mut out = vec![0u8; nbl * IQ3XXS_BLOCK_BYTES];

    for ibl in 0..nbl {
        let start = ibl * QK3XXS;
        let end = (start + QK3XXS).min(data.len());
        // Zero-pad the final partial block so the full 256-weight encoder path
        // runs unchanged; the padding lands in the unused tail and round-trips
        // to zeros.
        let mut xbl_buf = [0.0f32; QK3XXS];
        xbl_buf[..end - start].copy_from_slice(&data[start..end]);
        let xbl = &xbl_buf[..];
        // Scratch block: [0..64] grid indices, [64..96] scales_and_signs.
        let mut q3 = [0u8; 96];
        let mut scales = [0.0f32; N_SUB];
        let mut max_scale = 0.0f32;

        for ib in 0..N_SUB {
            let xb = &xbl[32 * ib..32 * ib + 32];
            let mut weight = [0.0f32; 32];
            let mut waux = [0.0f32; 32];
            for i in 0..32 {
                weight[i] = xb[i] * xb[i];
                waux[i] = weight[i].sqrt();
            }

            // Magnitudes, built before the sign pass because the parity
            // correction negates one of them.
            let mut xval = [0.0f32; 32];
            for i in 0..32 {
                xval[i] = xb[i].abs();
            }

            // Signs: one bit per weight, with a parity correction so each group
            // of eight carries an even number of flips. The reference stores the
            // result as a 7-bit index into ksigns_iq2xs, not as a bitmask.
            let mut block_signs = [0u8; 4];
            for k in 0..4 {
                let mut nflip = 0usize;
                let mut s = 0u8;
                for i in 0..8 {
                    if xb[8 * k + i] < 0.0 {
                        nflip += 1;
                        s |= 1 << i;
                    }
                }
                if nflip % 2 == 1 {
                    let mut imin = 0;
                    let mut min = weight[8 * k] * xb[8 * k] * xb[8 * k];
                    for i in 1..8 {
                        let ax = weight[8 * k + i] * xb[8 * k + i] * xb[8 * k + i];
                        if ax < min {
                            min = ax;
                            imin = i;
                        }
                    }
                    s ^= 1 << imin;
                    // The reference also negates the magnitude: the parity
                    // correction exists to make the 8-bit sign pattern
                    // representable in ksigns_iq2xs, and the flipped element
                    // must be quantized as negative or the grid search sees the
                    // wrong magnitude.
                    xval[8 * k + imin] = -xval[8 * k + imin];
                }
                block_signs[k] = s & 127;
            }

            let mut codes = [0i8; 32];

            let max = xval.iter().fold(0.0f32, |m, v| m.max(*v));
            if max < GROUP_MAX_EPS {
                scales[ib] = 0.0;
                continue;
            }

            // Optimise the scale over 31 candidates. `best` tracks
            // `scale*sumqx` and the acceptance test is the reference's
            // `sumqx^2 > best*sumq2`, i.e. correlation against the grid.
            let mut best = 0.0f64;
            let mut scale = max / (2 * KMAX_Q - 1) as f32;
            let mut is_on_grid = [true; 8];

            for is in -15..=15 {
                let id = (2.0 * KMAX_Q as f32 - 1.0 + is as f32 * 0.2) / max;
                let this_scale = 1.0 / id;
                let mut codes_aux = [0i8; 32];
                let mut on_grid_aux = [true; 8];

                for k in 0..8 {
                    for i in 0..4 {
                        let l = (0.5 * (id * xval[4 * k + i] - 1.0)).round();
                        codes_aux[4 * k + i] = l.max(0.0).min((KMAX_Q - 1) as f32) as i8;
                    }
                    let mut u = 0u16;
                    for i in 0..4 {
                        u |= (codes_aux[4 * k + i] as u16) << (3 * i);
                    }
                    let grid_index = KMAP_Q3XS[u as usize];
                    on_grid_aux[k] = true;
                    if grid_index < 0 {
                        on_grid_aux[k] = false;
                        iq3_find_best_neighbour(
                            (-grid_index - 1) as usize,
                            &xval[4 * k..4 * k + 4],
                            &waux[4 * k..4 * k + 4],
                            this_scale,
                            &mut codes_aux[4 * k..4 * k + 4],
                        );
                    }
                }

                let mut sumqx = 0.0f64;
                let mut sumq2 = 0.0f64;
                for i in 0..32 {
                    let w = weight[i] as f64;
                    let q = (2 * codes_aux[i] + 1) as f64;
                    sumqx += w * xval[i] as f64 * q;
                    sumq2 += w * q * q;
                }
                if sumq2 > 0.0 && sumqx * sumqx > best * sumq2 {
                    // The accepted scale is the least-squares optimum for the
                    // accepted codes, NOT the candidate scale that produced
                    // them. Keeping the candidate scale lets a badly-scaled
                    // candidate win the correlation test and lock in poor codes.
                    scale = (sumqx / sumq2) as f32;
                    best = scale as f64 * sumqx;
                    codes = codes_aux;
                    is_on_grid = on_grid_aux;
                }
            }

            // Re-resolve the groups that landed off-grid, now that the scale is fixed.
            let n_not_ongrid = is_on_grid.iter().filter(|&&b| !b).count();
            if n_not_ongrid > 0 && scale > 0.0 {
                let id = 1.0 / scale;
                for k in 0..8 {
                    if is_on_grid[k] {
                        continue;
                    }
                    for i in 0..4 {
                        let l = (0.5 * (id * xval[4 * k + i] - 1.0)).round();
                        codes[4 * k + i] = l.max(0.0).min((KMAX_Q - 1) as f32) as i8;
                    }
                    let mut u = 0u16;
                    for i in 0..4 {
                        u |= (codes[4 * k + i] as u16) << (3 * i);
                    }
                    let mut grid_index = KMAP_Q3XS[u as usize];
                    if grid_index < 0 {
                        grid_index = iq3_find_best_neighbour(
                            (-grid_index - 1) as usize,
                            &xval[4 * k..4 * k + 4],
                            &waux[4 * k..4 * k + 4],
                            scale,
                            &mut codes[4 * k..4 * k + 4],
                        );
                    }
                    let pg = &KGRID_Q3XS[grid_index as usize].to_le_bytes();
                    for i in 0..4 {
                        codes[4 * k + i] = ((pg[i] - 1) / 2) as i8;
                    }
                }
                let mut sumqx = 0.0f64;
                let mut sumq2 = 0.0f64;
                for i in 0..32 {
                    let w = weight[i] as f64;
                    let q = (2 * codes[i] + 1) as f64;
                    sumqx += w * xval[i] as f64 * q;
                    sumq2 += w * q * q;
                }
                if sumq2 > 0.0 {
                    scale = (sumqx / sumq2) as f32;
                }
            }

            // A negative scale cannot be stored in the 4-bit field; the reference
            // flips it and inverts every sign to compensate.
            if scale < 0.0 {
                scale = -scale;
                for k in 0..4 {
                    block_signs[k] = (!block_signs[k]) & 127;
                }
            }

            for k in 0..8 {
                let mut u = 0u16;
                for i in 0..4 {
                    u |= (codes[4 * k + i] as u16) << (3 * i);
                }
                let grid_index = KMAP_Q3XS[u as usize];
                if grid_index < 0 {
                    // The reference GGML_ABORTs here. Unreachable if the tables are
                    // correct, so treat it as a table bug rather than a data problem.
                    return Err(Error::Backend(format!(
                        "quantize_iq3xxs: packed pattern {u:#06x} is off-grid with no neighbours"
                    )));
                }
                q3[8 * ib + k] = grid_index as u8;
            }

            let mut aux = 0u32;
            aux |= block_signs[0] as u32;
            aux |= (block_signs[1] as u32) << 7;
            aux |= (block_signs[2] as u32) << 14;
            aux |= (block_signs[3] as u32) << 21;
            q3[64 + 4 * ib..68 + 4 * ib].copy_from_slice(&aux.to_le_bytes());
            scales[ib] = scale;
            max_scale = max_scale.max(scale);
        }

        if max_scale == 0.0 {
            // All sub-blocks were below GROUP_MAX_EPS: the reference leaves the
            // block zeroed and advances.
            continue;
        }

        let d = max_scale / 31.0;
        let dh = f32_to_f16(d * 1.0125);
        let id = 1.0 / d;
        for ib in 0..N_SUB {
            let l = (0.5 * (id * scales[ib] - 1.0)).round();
            let l = l.max(0.0).min(15.0) as u32;
            let mut aux = u32::from_le_bytes(q3[64 + 4 * ib..68 + 4 * ib].try_into().unwrap());
            aux |= l << 28;
            q3[64 + 4 * ib..68 + 4 * ib].copy_from_slice(&aux.to_le_bytes());
        }

        out[ibl * IQ3XXS_BLOCK_BYTES..ibl * IQ3XXS_BLOCK_BYTES + 2]
            .copy_from_slice(&dh.to_le_bytes());
        out[ibl * IQ3XXS_BLOCK_BYTES + 2..(ibl + 1) * IQ3XXS_BLOCK_BYTES].copy_from_slice(&q3);
    }

    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The block size is the whole point of the fix: the old encoder emitted 96
    /// bytes per block, which `dequant_iq3xxs` rejects outright.
    #[test]
    fn iq3xxs_block_is_98_bytes() {
        let n = 256;
        let w: Vec<f32> = (0..n).map(|i| (i as f32 * 0.37).sin() * 3.0).collect();
        let packed = quantize_iq3xxs(&w).expect("quantize_iq3xxs");
        assert_eq!(
            packed.len(),
            IQ3XXS_BLOCK_BYTES,
            "block must be 98 bytes (2 + 96), not the 96 the old encoder wrote"
        );
    }

    /// Quantize -> dequantize must land back near the source. This is the
    /// round-trip the old encoder could not perform at all, so it is the
    /// strongest single assertion available.
    #[test]
    fn iq3xxs_round_trips_through_the_reference_decoder() {
        let n = 256;
        let w: Vec<f32> = (0..n)
            .map(|i| (i as f32 * 0.11).sin() * 2.0 + (i as f32 * 0.031).cos())
            .collect();
        let packed = quantize_iq3xxs(&w).expect("quantize_iq3xxs");
        let back = crate::dequant_iq3xxs(&packed, n).expect("dequant_iq3xxs");

        // IQ3_XXS is ~3 bpw, so per-element error is a sizeable fraction of the
        // signal. Bound it relative to the peak rather than absolutely.
        let peak = w.iter().fold(0.0f32, |m, v| m.max(v.abs()));
        assert!(peak > 0.5, "fixture must carry real signal");
        let worst = w
            .iter()
            .zip(back.iter())
            .map(|(a, b)| (a - b).abs())
            .fold(0.0f32, f32::max);
        assert!(
            worst <= 0.35 * peak,
            "round-trip error {worst} exceeds 35% of peak {peak}"
        );
    }

    /// The neighbour table is only reachable for off-grid patterns, so assert it
    /// is actually populated -- an empty table would silently degrade every
    /// off-grid group to a wrong grid point.
    #[test]
    fn iq3xxs_neighbour_table_is_populated() {
        let off_grid = KMAP_Q3XS.iter().filter(|&&v| v < 0).count();
        assert!(
            off_grid > 0,
            "expected some off-grid patterns to need the neighbour table"
        );
        // Every off-grid entry must resolve to a real neighbour.
        for (i, &v) in KMAP_Q3XS.iter().enumerate() {
            if v >= 0 {
                continue;
            }
            let offset = (-v - 1) as usize;
            assert!(
                offset < KNEIGHBORS_Q3XS.len(),
                "pattern {i:#06x} points past the neighbour table"
            );
            assert!(
                KNEIGHBORS_Q3XS[offset] > 0,
                "pattern {i:#06x} has an empty neighbour list"
            );
        }
    }

    /// The map and the grid must agree: every on-grid entry must name a grid
    /// point whose packed codes re-encode to that same index.
    #[test]
    fn iq3xxs_map_agrees_with_the_grid() {
        for &v in KMAP_Q3XS.iter() {
            if v < 0 {
                continue;
            }
            let pg = &KGRID_Q3XS[v as usize].to_le_bytes();
            let mut u = 0u16;
            for k in 0..4 {
                u |= (((pg[k] - 1) / 2) as u16) << (3 * k);
            }
            assert_eq!(
                KMAP_Q3XS[u as usize], v,
                "grid point {v} re-encodes to pattern {u:#06x}, which maps to {}",
                KMAP_Q3XS[u as usize]
            );
        }
    }
}
